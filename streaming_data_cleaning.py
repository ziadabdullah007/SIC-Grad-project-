    "def merge_by_kafka_position(table_name, source_df):\n",
    "    \"\"\"Idempotently insert records based on the Kafka message position.\"\"\"\n",
    "    if source_df.limit(1).count() == 0:\n",
    "        return\n",
    "\n",
    "    target = DeltaTable.forName(spark, table_name)\n",
    "    (\n",
    "        target.alias(\"t\")\n",
    "        .merge(\n",
    "            source_df.alias(\"s\"),\n",
    "            \"\"\"\n",
    "            t.kafka_topic = s.kafka_topic\n",
    "            AND t.kafka_partition = s.kafka_partition\n",
    "            AND t.kafka_offset = s.kafka_offset\n",
    "            \"\"\"\n",
    "        )\n",
    "        .whenNotMatchedInsertAll()\n",
    "        .execute()\n",
    "    )\n",
    "\n",
    "\n",
    "def process_batch(batch_df, batch_id):\n",
    "    if batch_df.limit(1).count() == 0:\n",
    "        return\n",
    "\n",
    "    all_rows = parse_and_validate(batch_df).withColumn(\n",
    "        \"batch_id\", F.lit(int(batch_id)).cast(\"long\")\n",
    "    )\n",
    "\n",
    "    invalid = all_rows.filter(F.col(\"error_reason\") != \"\")\n",
    "    dlq_rows = invalid.select(\n",
    "        \"original_payload\", \"ingestion_time\", \"batch_id\",\n",
    "        \"error_type\", \"error_reason\",\n",
    "        \"kafka_topic\", \"kafka_partition\", \"kafka_offset\"\n",
    "    )\n",
    "    merge_by_kafka_position(\"telemetry_dlq\", dlq_rows)\n",
    "\n",
    "    valid = (\n",
    "        all_rows.filter(F.col(\"error_reason\") == \"\")\n",
    "        .withColumnRenamed(\"timestamp_parsed\", \"parsed_timestamp\")\n",
    "        .withColumnRenamed(\"date_parsed\", \"parsed_date\")\n",
    "    )\n",
    "\n",
    "    if valid.limit(1).count() == 0:\n",
    "        print(f\"Batch {batch_id}: invalid={invalid.count()}, valid=0\")\n",
    "        return\n",
    "\n",
    "    # A business event is identified by server, experiment, and event timestamp.\n",
    "    duplicate_key = [\"server_id\", \"experiment_id\", \"parsed_timestamp\"]\n",
    "    batch_window = Window.partitionBy(*duplicate_key).orderBy(\n",
    "        F.col(\"kafka_partition\").asc(),\n",
    "        F.col(\"kafka_offset\").asc()\n",
    "    )\n",
    "\n",
    "    ranked = (\n",
    "        valid\n",
    "        .withColumn(\"_row_num\", F.row_number().over(batch_window))\n",
    "        .withColumn(\n",
    "            \"duplicate_key\",\n",
    "            F.concat_ws(\n",
    "                \"|\", F.col(\"server_id\"), F.col(\"experiment_id\"),\n",
    "                F.date_format(\"parsed_timestamp\", \"yyyy-MM-dd HH:mm:ss\")\n",
    "            )\n",
    "        )\n",
    "    )\n",
    "\n",
    "    existing_keys = (\n",
    "        spark.table(\"telemetry_processed\")\n",
    "        .select(\n",
    "            \"server_id\", \"experiment_id\",\n",
    "            F.col(\"timestamp\").alias(\"parsed_timestamp\")\n",
    "        )\n",
    "        .dropDuplicates()\n",
    "    )\n",
    "\n",
    "    first_rows = ranked.filter(F.col(\"_row_num\") == 1)\n",
    "    new_first_rows = first_rows.join(existing_keys, on=duplicate_key, how=\"left_anti\")\n",
    "    later_rows = ranked.filter(F.col(\"_row_num\") > 1)\n",
    "    already_seen_rows = first_rows.join(existing_keys, on=duplicate_key, how=\"inner\")\n",
    "\n",
    "    duplicates = (\n",
    "        later_rows.withColumn(\n",
    "            \"duplicate_reason\",\n",
    "            F.lit(\"Duplicate business key within the same micro-batch\")\n",
    "        )\n",
    "        .unionByName(\n",
    "            already_seen_rows.withColumn(\n",
    "                \"duplicate_reason\",\n",
    "                F.lit(\"Business key already exists in processed table\")\n",
    "            ),\n",
    "            allowMissingColumns=True\n",
    "        )\n",
    "    )\n",
    "\n",
    "    duplicate_sink = duplicates.select(\n",
    "        \"original_payload\", \"ingestion_time\", \"batch_id\",\n",
    "        \"duplicate_key\", \"duplicate_reason\",\n",
    "        \"kafka_topic\", \"kafka_partition\", \"kafka_offset\"\n",
    "    )\n",
    "    merge_by_kafka_position(\"telemetry_duplicates\", duplicate_sink)\n",
    "\n",
    "    processed = new_first_rows.select(\n",
    "        F.col(\"parsed_timestamp\").alias(\"timestamp\"),\n",
    "        F.col(\"parsed_date\").alias(\"date\"),\n",
    "        \"time\", \"server_id\", \"model_id\", \"experiment_id\",\n",
    "        F.col(\"gpu_count\").cast(\"int\"),\n",
